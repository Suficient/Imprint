use crate::issuer::attributes::{self, CountryAttribute, DOBAttribute, Gender, GenderAttribute, NameAttribute};

/*
    ATTRIBUTESET

    This struct is a set of 4 attributes: name, dob, gender, country.
    A new attributeset struct is generated by sending each attribute as a string.
    attribute validation lives here. Generation code will take input and convert
    it into an AttributeSet.

    Each attribute must be ordered deterministically, and must conform to the schema.
    Errors relating to attribute validity are handled here.

*/
pub struct AttributeSet {
    name: NameAttribute,
    gender: GenderAttribute,
    dob: DOBAttribute,
    country: CountryAttribute
}

